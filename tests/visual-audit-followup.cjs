const { chromium } = require('C:/Users/a/node_modules/playwright-core');
const fs = require('node:fs');
(async()=>{
 const browser=await chromium.launch({headless:true});
 const context=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
 const page=await context.newPage();
 const cdp=await context.newCDPSession(page);
 await page.goto('https://www.fungood.co.kr/claude_game/',{waitUntil:'networkidle'});
 const handle=await page.locator('.panel-handle').boundingBox();
 const x=handle.x+20,y=handle.y+2;
 await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x,y}]});
 await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x,y:y+40}]});
 await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
 const touchMinimized=await page.locator('#bottom-panel').evaluate(el=>el.classList.contains('minimized'));
 await page.screenshot({path:'docs/qa/2026-10-03/13-touch-panel.png'});
 await page.locator('canvas').tap({position:{x:180,y:100}});
 await page.waitForTimeout(200);
 await page.locator('canvas').tap({position:{x:320,y:18}});
 await page.waitForTimeout(200);
 const exitRestoresPanel=await page.locator('#bottom-panel').evaluate(el=>getComputedStyle(el).display!=='none');
 await page.locator('canvas').tap({position:{x:180,y:100}});
 await page.waitForTimeout(1000);
 await page.reload({waitUntil:'networkidle'});
 const saved=await page.evaluate(()=>JSON.parse(localStorage.getItem('claude_game_save_v1')));
 const reloadReturnsIdle=await page.locator('#bottom-panel').evaluate(el=>getComputedStyle(el).display!=='none');
 const result={touchMinimized,exitRestoresPanel,reloadReturnsIdle,savedRunState:saved?.runState,savedHasCombatSession:!!saved?.combatSession};
 fs.writeFileSync('docs/qa/2026-10-03/followup.json',JSON.stringify(result,null,2));
 console.log(result);
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
